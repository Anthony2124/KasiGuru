#!/usr/bin/env node
/**
 * Copies the shared web design layer into both surfaces.
 *
 * `admin-website/download` and `admin-website/admin` are separate Vercel projects with no build step,
 * so they cannot import a stylesheet from each other or from a common path at request time. The
 * canonical files live in `admin-website/shared/` and are copied into each surface's `css/` folder.
 *
 * The duplication is the honest cost of two static deploys. This script plus its `--check` mode is
 * what stops the copies drifting — which is exactly what happened before, leaving two stylesheets
 * that were 80% byte-identical and subtly different in the rest.
 *
 *   node scripts/sync-web-shared.js          copy shared -> both surfaces
 *   node scripts/sync-web-shared.js --check  exit 1 if any copy is stale (used by CI)
 */

const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const sharedDir = path.join(repoRoot, 'admin-website', 'shared');
const targets = [
  path.join(repoRoot, 'admin-website', 'download', 'css'),
  path.join(repoRoot, 'admin-website', 'admin', 'css'),
];
const files = ['tokens.css', 'components.css'];

const checkOnly = process.argv.includes('--check');
const banner = '/* GENERATED by scripts/sync-web-shared.js from admin-website/shared/. Do not edit. */\n';

let stale = 0;
let written = 0;

for (const file of files) {
  const sourcePath = path.join(sharedDir, file);
  if (!fs.existsSync(sourcePath)) {
    console.error('missing shared source: ' + sourcePath);
    process.exit(1);
  }
  const contents = banner + fs.readFileSync(sourcePath, 'utf8');

  for (const dir of targets) {
    const destPath = path.join(dir, file);
    const current = fs.existsSync(destPath) ? fs.readFileSync(destPath, 'utf8') : null;

    if (current === contents) continue;

    if (checkOnly) {
      stale += 1;
      console.error('STALE: ' + path.relative(repoRoot, destPath));
      continue;
    }

    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(destPath, contents, 'utf8');
    written += 1;
    console.log('wrote ' + path.relative(repoRoot, destPath));
  }
}

if (checkOnly) {
  if (stale > 0) {
    console.error('\n' + stale + ' copied file(s) differ from admin-website/shared/.');
    console.error('Run: node scripts/sync-web-shared.js   and commit the result.');
    process.exit(1);
  }
  console.log('shared web layer is in sync');
} else {
  console.log(written === 0 ? 'already in sync' : 'synced ' + written + ' file(s)');
}
